async page => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.locator('#add-section').click();
  await page.locator('#section-name').fill('PDF 测试');
  await page.locator('#save-section').click();
  await page.locator('#sections [data-section]').last().click();
  await page.locator('#add-record').click();
  await page.locator('#record-title').fill('习题');
  await page.locator('#back-zone').click();

  const record = page.locator('#records [data-record]').last();
  const box = await record.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.waitForTimeout(720);
  if (await page.locator('#record-color-modal').isHidden()) throw new Error('Long press did not open record colors');
  await page.mouse.up();
  await page.locator('#record-color-picks [data-level="red"]').click();
  if (!(await record.getAttribute('class')).includes('level-red')) throw new Error('Record color was not saved');
  await record.click();
  await page.locator('#add-tip').click();
  if (await page.locator('#tip-document .tip-ink').count() !== 1 || await page.locator('#tip-document .tip-text').count()) throw new Error('New tip is not handwriting first');
  await page.locator('#tip-title').fill('第 1 题');
  await page.locator('.brush-settings summary').click();
  await page.locator('[data-brush]').selectOption('pencil');
  await page.locator('[data-ink-size]').fill('14');
  await page.locator('[data-ink-pressure]').fill('80');
  await page.locator('.brush-settings summary').click();
  const ink = await page.locator('#tip-document .tip-ink').boundingBox();
  await page.mouse.move(ink.x + 30, ink.y + 35);
  await page.mouse.down();
  await page.mouse.move(ink.x + 140, ink.y + 95, { steps: 8 });
  await page.mouse.up();
  const stroke = await page.evaluate(() => tipDraft.blocks[0].strokes[0]);
  if (stroke.brush !== 'pencil' || stroke.size !== 14 || stroke.sensitivity !== 80 || stroke.points.length < 2) throw new Error('Brush settings were not captured');

  await page.locator('#tip-other-file').setInputFiles('..\\mobile-build-tools\\exported-algebra.pdf');
  await page.locator('[data-pdf-status]').filter({ hasText: '1 / 1' }).waitFor({ timeout: 15000 });
  await page.locator('.pdf-ink').evaluate(element => element.scrollIntoView({ block: 'start' }));
  const pdfInk = await page.locator('.pdf-ink').boundingBox();
  await page.mouse.move(pdfInk.x + 45, pdfInk.y + 180);
  await page.mouse.down();
  await page.mouse.move(pdfInk.x + 150, pdfInk.y + 250, { steps: 8 });
  await page.mouse.up();
  const annotations = await page.evaluate(() => tipDraft.blocks.find(block => block.type === 'pdf').annotations[1].strokes.length);
  if (annotations !== 1) throw new Error('PDF handwriting was not captured');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('[data-pdf-export]').click();
  const download = await downloadPromise;
  if (!download.suggestedFilename().endsWith('-批注.pdf')) throw new Error('Annotated PDF export failed');
  await download.saveAs('..\\mobile-build-tools\\annotated-flow-test.pdf');
  await page.locator('#save-tip').click();
  await page.reload();
  await page.locator('#sections [data-section]').last().click();
  await page.locator('#records [data-record]').last().click();
  await page.locator('#tips [data-tip]').last().click();
  await page.locator('#tips [data-tip]').last().click();
  await page.locator('[data-pdf-status]').filter({ hasText: '1 / 1' }).waitFor({ timeout: 15000 });
  const persisted = await page.evaluate(() => tipDraft.blocks.find(block => block.type === 'pdf').annotations[1].strokes.length);
  if (persisted !== 1) throw new Error('PDF annotation did not persist');
  if (errors.length) throw new Error(`Page errors: ${errors.join('; ')}`);
  return { recordColor: 'red', brush: stroke.brush, strokePoints: stroke.points.length, pdfStrokes: persisted, export: download.suggestedFilename() };
}
